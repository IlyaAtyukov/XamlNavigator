using System.Threading.Tasks;
using XamlNavigator.Abstractions;
using XamlNavigator.Attributes;
using XamlNavigator.Core;

namespace XamlNavigator.Samples.ViewModels
{
    [ChildOf(typeof(MainViewModel), Cluster = 9, Order = 0, DisplayName = "About", IconKey = "ℹ")]
    public class AboutViewModel : BaseContentViewModel
    {
        private string _cameFrom = "from the menu";

        public AboutViewModel(INavigationOrchestrator navigator)
        {
            BackCommand = new RelayCommand(_ => navigator.NavigateBackAsync(), _ => navigator.CanNavigateBack);
        }

        public string Text =>
            "The view models in this sample live in the shared XamlNavigator.Samples.Shared library and run unchanged " +
            "in both WPF and .NET MAUI. The menu on the left is built from [ChildOf] attributes and from pages defined in data: " +
            "\"Categories\", \"Products\", and \"Showcase\" are generated by the navigator itself — with search, field validation, " +
            "computed fields, and highlighting.";

        public string CameFrom
        {
            get { return _cameFrom; }
            private set { SetProperty(ref _cameFrom, value); }
        }

        public RelayCommand BackCommand { get; }

        public override async Task OnAppearingAsync()
        {
            await base.OnAppearingAsync();
            CameFrom = HasParam<string>() ? "Opened " + TakeParam<string>() + "." : "Opened from the menu.";
            BackCommand.RaiseCanExecuteChanged();
        }
    }
}
